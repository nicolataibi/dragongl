#ifndef PROTOCOL_H
#define PROTOCOL_H

/*
 * Wire protocol.
 *
 * The messages are defined once, in protocol/messages.json: the version,
 * the message types, the field sizes and the in-memory structs come from
 * protocol_gen.h, the codec from wire.h, both generated by
 * tools/gen_protocol.py. None of the structs is ever sent as raw bytes:
 * every message is encoded field by field, little-endian, with explicit
 * widths. See PROTOCOL.md for the byte-level description.
 *
 * Every connection is TLS 1.3 with the ALPN protocol "dragongl/<version>"
 * (tls_common.h): an old client and a new server fail at the handshake,
 * and a frame of another version is a protocol error.
 * v5: TLS; the message table; the frames of v4.
 * v4: explicit serialization, 8-byte header, length-prefixed strings,
 * 64-byte credential fields, MSG_COMBAT_EVENT.
 *
 * Frame:  u16 version | u16 type | u32 payload length | payload
 */

#include <stdint.h>
#include "map.h"

typedef uint16_t MsgType;

#define WIRE_HEADER_SIZE 8

/*Decoded frame header.*/
typedef struct {
    uint16_t version;
    MsgType type;
    uint32_t length; /*payload bytes after the header*/
} MsgHeader;

/*MSG_COMBAT_EVENT kinds: what the floating combat text shows, said by the
 * server (never guessed from the wording of MSG_TEXT lines). entity_id is
 * the entity the number belongs to (the player, or the monster that was
 * hit), 0 if none.*/
typedef enum {
    COMBAT_EV_DAMAGE_TAKEN = 1, /* the player lost `amount` HP */
    COMBAT_EV_DAMAGE_DEALT = 2, /* the player hit a monster for `amount` */
    COMBAT_EV_CRITICAL = 3,     /* ... with a critical hit */
    COMBAT_EV_MISS_TAKEN = 4,   /* a monster missed the player */
    COMBAT_EV_MISS_DEALT = 5,   /* the player missed */
    COMBAT_EV_HEAL = 6,         /* the player recovered `amount` HP */
    COMBAT_EV_GOLD = 7,         /* the player picked up `amount` gold */
    COMBAT_EV_LEVEL_UP = 8,     /* the player reached level `amount` */
    COMBAT_EV_MAX = 8
} CombatEventKind;

/* Values for MsgState.shop_spec - they must match the
 * MerchantSpecialization enum in src/server/server_entities.h.
 * The client only needs to recognize the martial bookshop to
 * draw its unique sprite.*/
#define SHOP_SPEC_NONE          (-1)
#define SHOP_SPEC_BOOKS_MARTIAL 11

#include "protocol_gen.h"

#endif // PROTOCOL_H
