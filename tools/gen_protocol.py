def clang_format():
    """clang-format 18 (the version of .clang-format and CI), or exit."""
    for cand in ("clang-format-18", "clang-format"):
        try:
            out = subprocess.run([cand, "--version"], capture_output=True, text=True).stdout
        except OSError:
            continue
        if "version 18." in out:
            return cand
    sys.exit("gen_protocol: clang-format 18 is needed to format the generated C files")


def formatted(rel, text, tool):
    """The C files go through clang-format: they follow the tree's style."""
    if not rel.endswith((".c", ".h")):
        return text
    return subprocess.run([tool, "--assume-filename=" + os.path.join(ROOT, rel)], input=text,
                          capture_output=True, text=True, check=True, cwd=ROOT).stdout


def outputs():
    vec = vectors()
    with open(os.path.join(ROOT, "PROTOCOL.md"), encoding="utf-8") as f:
        md = f.read()
    return {
        "include/protocol_gen.h": gen_protocol_header(),
        "include/wire.h": gen_wire_header(),
        "src/shared/wire.c": gen_wire_c(),
        "tests/test_protocol_conformance.c": gen_conformance(vec),
        "tests/protocol_vectors.json": json.dumps(vec, indent=2, ensure_ascii=False) + "\n",
        "PROTOCOL.md": gen_protocol_md(md),
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if a generated file is stale")
    args = ap.parse_args()
    stale = []
    tool = clang_format()
    for rel, text in outputs().items():
        text = formatted(rel, text, tool)
        path = os.path.join(ROOT, rel)
        old = None
        if os.path.exists(path):
            with open(path, encoding="utf-8") as f:
                old = f.read()
        if old == text:
            continue
        if args.check:
            stale.append(rel)
        else:
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
            print("written: %s" % rel)
    if stale:
        print("gen_protocol: stale, run tools/gen_protocol.py: " + ", ".join(stale))
        return 1
    if args.check:
        print("gen_protocol: %d messages, generated files up to date" % len(SPEC.messages))
    return 0


if __name__ == "__main__":
    sys.exit(main())
