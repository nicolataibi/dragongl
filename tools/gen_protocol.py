def type_text(f):
    t = f["type"]
    if t == "str":
        base = "str(%d)" % (SPEC.value(f["cap"]) - 1)
    elif t == "bytes":
        base = "u8[%s]" % f["length"].replace(" ", "")
    elif t == "records":
        base = "%s count, then records" % f["count_type"]
    elif t == "unit8":
        base = "u8 (0..1 × 255)"
    else:
        base = t
    if "count" in f:
        base += " × %s" % c_value(f["count"])
    return base


def num(expr):
    """A table value as a number, with the constant it comes from."""
    if isinstance(expr, int):
        return str(expr)
    return "%d (`%s`)" % (SPEC.value(expr), expr)


def range_text(f):
    if f["type"] == "records":
        return "%s..%s records" % (num(f["min"]), num(f["max"]))
    if f["type"] == "bytes" and f.get("max") is not None:
        return "each ≤ %s" % num(f["max"])
    if not explicit_range(f):
        return ""
    lo = num(f["min"]) if f.get("min") is not None else ""
    hi = num(f["max"]) if f.get("max") is not None else ""
    if lo and hi:
        return "%s..%s" % (lo, hi)
    return "≥ %s" % lo if lo else "≤ %s" % hi


def gen_doc_messages():
    out = ["| Value | Identifier | Direction | Max payload | Description |\n",
           "|:---:|:---|:---:|---:|:---|\n"]
    for m in SPEC.messages:
        out.append("| `%d` | [`MSG_%s`](#msg_%s) | %s | %d | %s |\n"
                   % (m["id"], m["name"], lower(m["name"]), DIR_TEXT[m["dir"]],
                      SPEC.max_payload(m), m["doc"]))
    return "".join(out)


def gen_doc_payloads():
    out = ["Notation: `i8 i16 i32` signed, `u8 u16 u32 u64` unsigned, `bool` one byte 0/1, "
           "`f32` IEEE-754 bits, `str(N)` a string of at most N bytes (`u8` length, then the "
           "bytes, no NUL). Fields follow each other in the order of the table, nothing "
           "between them. A value outside its range is a protocol error.\n"]
    for name, rec in SPEC.records.items():
        out.append("\n**`%s`** (%d bytes): %s\n\n| Field | Type | Range |\n|:---|:---|:---|\n"
                   % (name, SPEC.record_size(name), rec["doc"]))
        for f in rec["fields"]:
            out.append("| `%s` | `%s` | %s |\n" % (f["name"], type_text(f), range_text(f)))
    for m in SPEC.messages:
        out.append("\n### MSG_%s\n\n%s (%s, type %d, at most %d bytes).\n\n"
                   % (m["name"], m["doc"], DIR_TEXT[m["dir"]], m["id"], SPEC.max_payload(m)))
        out.append("| Field | Type | Range | Notes |\n|:---|:---|:---|:---|\n")
        for f in m["fields"]:
            extra = f.get("doc", "")
            if f["type"] == "records":
                extra = ("`%s` records" % f["record"]) + ((": " + extra) if extra else "")
            out.append("| `%s` | `%s` | %s | %s |\n" % (f["name"], type_text(f), range_text(f), extra))
        for c in m.get("checks", []):
            out.append("\nAlso: `%s` (%s).\n" % (c["expr"], c["doc"]))
        if m.get("notes"):
            out.append("\n%s\n" % m["notes"])
    return "".join(out)


def splice(text, marker, content):
    begin = "<!-- BEGIN GENERATED: %s -->\n" % marker
    end = "<!-- END GENERATED: %s -->" % marker
    a, b = text.index(begin) + len(begin), text.index(end)
    return text[:a] + content + text[b:]


def gen_protocol_md(current):
    text = splice(current, "messages", gen_doc_messages())
    text = splice(text, "payloads", gen_doc_payloads())
    text = re.sub(r"Current protocol version: \*\*`PROTOCOL_VERSION \d+`\*\*",
                  "Current protocol version: **`PROTOCOL_VERSION %d`**" % SPEC.version, text)
    return text


