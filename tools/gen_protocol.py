"""Generate the wire protocol from its table, protocol/messages.json.

    tools/gen_protocol.py           write the generated files
    tools/gen_protocol.py --check   exit 1 if one of them is stale (CI)

Generated, never edited by hand:
  include/protocol_gen.h            version, message ids, sizes, structs
  include/wire.h                    the codec interface
  src/shared/wire.c                 the codec: encoders and strict decoders
  tests/test_protocol_conformance.c every example of the table encoded and
                                    decoded by the C codec, every invalid
                                    variant refused
  tests/protocol_vectors.json       the same vectors, for the Python codec
  PROTOCOL.md                       the sections between the markers
                                    <!-- BEGIN GENERATED: ... --> / END

The Python codec (protocol/codec.py) reads the table at run time, and the
vectors are computed with it: the C test checks that both codecs agree to
the byte.
"""

import argparse
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "protocol"))
import codec  # noqa: E402

BANNER = ("/* GENERATED by tools/gen_protocol.py from protocol/messages.json:\n"
          " * do not edit, change the table and run the generator. */\n")
LICENSE = ("/*\n * DRAGON GL - 3D ARCANE ENGINE\n * Copyright (C) 2026 Nicola Taibi\n"
           " * License: GPL-3.0-or-later\n */\n")

CTYPE = {"i8": "int", "i16": "int", "i32": "int", "u8": "int", "u16": "int", "bool": "int",
         "u32": "uint32_t", "u64": "uint64_t", "f32": "float", "unit8": "float"}
PUT = {"i8": "put_i8(w, {v})", "i16": "put_i16(w, {v})", "i32": "bw_i32(w, (int32_t){v})",
       "u8": "bw_u8(w, (uint8_t){v})", "u16": "bw_u16(w, (uint16_t){v})",
       "u32": "bw_u32(w, {v})", "u64": "bw_u64(w, {v})", "bool": "bw_bool(w, {v} != 0)",
       "f32": "put_f32(w, {v})", "unit8": "put_unit(w, {v})"}
GET = {"i8": "get_i8(&r)", "i16": "get_i16(&r)", "i32": "br_i32(&r)", "u8": "br_u8(&r)",
       "u16": "br_u16(&r)", "u32": "br_u32(&r)", "u64": "br_u64(&r)",
       "bool": "br_bool(&r) ? 1 : 0", "f32": "get_f32(&r)", "unit8": "get_unit(&r)"}
DIR_TEXT = {"C2S": "C → S", "S2C": "S → C"}
DIR_C = {"C2S": "client -> server", "S2C": "server -> client"}

SPEC = codec.Spec()


def lower(name):
    return name.lower()


def c_expr(expr, fields, prefix="m->"):
    """A table expression in C: field names become members of *m."""
    if isinstance(expr, int):
        return str(expr)
    return re.sub(r"\b[a-z_][a-z0-9_]*\b",
                  lambda mo: prefix + mo.group(0) if mo.group(0) in fields else mo.group(0), expr)


def c_value(expr):
    return str(expr) if isinstance(expr, int) else expr


def explicit_range(field):
    return field.get("min") is not None or field.get("max") is not None


def range_cond(field, var):
    """C condition that var is in the field's declared range ('' if none)."""
    parts = []
    if field.get("min") is not None:
        parts.append("%s >= %s" % (var, c_value(field["min"])))
    if field.get("max") is not None:
        parts.append("%s <= %s" % (var, c_value(field["max"])))
    return " && ".join(parts)


# --- protocol_gen.h -------------------------------------------------------

def gen_protocol_header():
    out = [LICENSE, BANNER, """
/*
 * The message table of the wire protocol: version, message types, field
 * sizes and the in-memory form of every message. PROTOCOL.md describes
 * the encoding; include/wire.h encodes and decodes.
 */

#ifndef DRAGONGL_PROTOCOL_GEN_H
#define DRAGONGL_PROTOCOL_GEN_H

#include <stdint.h>

"""]
    out.append("#define PROTOCOL_VERSION %d\n\n" % SPEC.version)
    out.append("/* Message types. */\n")
    width = max(len(m["name"]) for m in SPEC.messages) + 4
    for m in SPEC.messages:
        out.append("#define %-*s %2d /* %s */\n" % (width, "MSG_" + m["name"], m["id"],
                                                   DIR_C[m["dir"]]))
    out.append("\n/* Field sizes (C arrays, NUL included: the wire carries size-1 bytes)\n"
               " * and limits. */\n")
    for k, v in SPEC.raw["constants"].items():
        out.append("#define %s %d /* %s */\n" % (k, v["value"], v["doc"]))
    out.append("\n")
    for name, rec in SPEC.records.items():
        out.append("/* %s */\ntypedef struct {\n" % rec["doc"])
        for f in rec["fields"]:
            out.append("    %s %s;\n" % (CTYPE[f["type"]], f["name"]))
        out.append("} %s;\n" % name)
        out.append("#define WIRE_%s_SIZE %d /* bytes of one record */\n\n"
                   % (re.sub(r"(?<!^)(?=[A-Z])", "_", name).upper(), SPEC.record_size(name)))
    for m in SPEC.messages:
        out.append("/* MSG_%s (%s):\n * %s. */\ntypedef struct {\n"
                   % (m["name"], DIR_C[m["dir"]], m["doc"].replace("`", "")))
        for f in m["fields"]:
            t = f["type"]
            if f.get("doc"):
                out.append("    /* %s */\n" % f["doc"].replace("`", ""))
            if t == "str":
                dims = "[%s]" % c_value(f["count"]) if "count" in f else ""
                out.append("    char %s%s[%s];\n" % (f["name"], dims, c_value(f["cap"])))
            elif t == "bytes":
                out.append("    const uint8_t *%s; /* %s bytes; after decoding they point into "
                           "the payload */\n" % (f["name"], f["length"]))
            elif t == "records":
                out.append("    int %s;\n" % f["count_name"])
                out.append("    %s %s[%s];\n" % (f["record"], f["name"], c_value(f["max"])))
            else:
                dims = "[%s]" % c_value(f["count"]) if "count" in f else ""
                out.append("    %s %s%s;\n" % (CTYPE[t], f["name"], dims))
        out.append("} %s;\n\n" % m["struct"])
    out.append("/* Largest payload of each message, and per direction. */\n")
    c2s = s2c = 0
    for m in SPEC.messages:
        size = SPEC.max_payload(m)
        out.append("#define WIRE_MAX_PAYLOAD_%s %du\n" % (m["name"], size))
        if m["dir"] == "C2S":
            c2s = max(c2s, size)
        else:
            s2c = max(s2c, size)
    out.append("#define WIRE_MAX_CLIENT_PAYLOAD %du /* sizes the server's receive buffer */\n" % c2s)
    out.append("#define WIRE_MAX_SERVER_PAYLOAD %du /* sizes the client's receive buffer */\n" % s2c)
    out.append("#define WIRE_MAX_PAYLOAD        %du\n" % max(c2s, s2c))
    out.append("\n#endif\n")
    return "".join(out)


# --- wire.h ---------------------------------------------------------------

def gen_wire_header():
    out = [LICENSE, BANNER, """
/*
 * Encoding and decoding of the wire protocol (PROTOCOL.md).
 *
 * wire_put_<msg>() appends ONE complete frame (header + payload) to a
 * BinWriter; false if a value is outside its range, the writer ran out of
 * memory or the payload would exceed WIRE_MAX_PAYLOAD (the writer then
 * keeps what it held before). Strings longer than their field are cut.
 *
 * wire_get_<msg>() decodes a payload (the bytes after the header) into the
 * struct; false for any malformed payload: truncated, with trailing bytes,
 * a string longer than its field, a count, enum, coordinate or other value
 * out of range. A false return is a protocol violation: the peer is
 * dropped.
 */

#ifndef DRAGONGL_WIRE_H
#define DRAGONGL_WIRE_H

#include "binio.h"
#include "protocol.h"

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

/* Decode the 8 header bytes at buf (no validation). */
void wire_read_header(const uint8_t *buf, MsgHeader *h);
/* Largest payload the server accepts for a message a client may send,
 * or 0 if a client may not send that type. */
uint32_t wire_client_payload_max(MsgType type);
/* Largest payload the client accepts for a message the server may send,
 * or 0 if the server may not send that type. */
uint32_t wire_server_payload_max(MsgType type);

"""]
    for m in SPEC.messages:
        n, s = lower(m["name"]), m["struct"]
        out.append("/* MSG_%s (%s) */\n" % (m["name"], DIR_TEXT[m["dir"]].replace("→", "->")))
        out.append("bool wire_put_%s(BinWriter *w, const %s *m);\n" % (n, s))
        out.append("bool wire_get_%s(const void *p, size_t n, %s *m);\n" % (n, s))
    out.append("\n#endif\n")
    return "".join(out)


# --- wire.c ---------------------------------------------------------------

WIRE_C_HELPERS = r"""
#include "wire.h"

#include <string.h>

/* The constants the table takes from other headers. */
%(asserts)s
/* --- Helpers ----------------------------------------------------------------- */

static void put_le32(uint8_t *p, uint32_t v) {
    for (int i = 0; i < 4; i++) {
        p[i] = (uint8_t)(v >> (8 * i));
    }
}

void wire_read_header(const uint8_t *buf, MsgHeader *h) {
    h->version = (uint16_t)(buf[0] | (buf[1] << 8));
    h->type = (MsgType)(buf[2] | (buf[3] << 8));
    h->length = (uint32_t)buf[4] | ((uint32_t)buf[5] << 8) | ((uint32_t)buf[6] << 16) |
                ((uint32_t)buf[7] << 24);
}

/* Header with a zero length; frame_end() patches it. Returns the offset of
 * the header in the writer. */
static size_t frame_begin(BinWriter *w, MsgType type) {
    size_t at = w->len;
    bw_u16(w, PROTOCOL_VERSION);
    bw_u16(w, type);
    bw_u32(w, 0);
    return at;
}

static bool frame_end(BinWriter *w, size_t at) {
    if (w->failed) {
        return false;
    }
    size_t payload = w->len - at - WIRE_HEADER_SIZE;
    if (payload > WIRE_MAX_PAYLOAD) {
        w->len = at; /* drop the frame, keep what was there before */
        return false;
    }
    put_le32(w->data + at + 4, (uint32_t)payload);
    return true;
}

/* String: u8 length + bytes. Longer strings are cut to cap-1 bytes. */
static void put_str(BinWriter *w, const char *s, size_t cap) {
    size_t n = s ? strnlen(s, cap - 1) : 0;
    if (n > 255) {
        n = 255;
    }
    bw_u8(w, (uint8_t)n);
    bw_bytes(w, s, n);
}

static void get_str(BinReader *r, char *out, size_t cap) {
    size_t n = br_u8(r);
    if (n >= cap) {
        r->failed = true;
        out[0] = '\0';
        return;
    }
    br_bytes(r, out, n);
    out[n] = '\0';
    if (r->failed) {
        out[0] = '\0';
    }
}

static void put_i8(BinWriter *w, int v) {
    bw_u8(w, (uint8_t)(int8_t)v);
}

static int get_i8(BinReader *r) {
    return (int8_t)br_u8(r);
}

static void put_i16(BinWriter *w, int v) {
    bw_u16(w, (uint16_t)(int16_t)v);
}

static int get_i16(BinReader *r) {
    return (int16_t)br_u16(r);
}

static void put_f32(BinWriter *w, float f) {
    uint32_t u;
    memcpy(&u, &f, sizeof(u));
    bw_u32(w, u);
}

static float get_f32(BinReader *r) {
    uint32_t u = br_u32(r);
    float f;
    memcpy(&f, &u, sizeof(f));
    return f;
}

/* A colour channel 0..1 as a byte. */
static void put_unit(BinWriter *w, float f) {
    if (!(f > 0.0f)) {
        f = 0.0f;
    }
    if (f > 1.0f) {
        f = 1.0f;
    }
    bw_u8(w, (uint8_t)(f * 255.0f + 0.5f));
}

static float get_unit(BinReader *r) {
    return (float)br_u8(r) / 255.0f;
}

static void begin_read(BinReader *r, const void *p, size_t n, void *out, size_t out_size) {
    memset(out, 0, out_size);
    br_init(r, p, n);
}

/* --- Limits ---------------------------------------------------------------- */

uint32_t wire_client_payload_max(MsgType type) {
    switch (type) {
%(client_cases)s    default:
        return 0;
    }
}

uint32_t wire_server_payload_max(MsgType type) {
    switch (type) {
%(server_cases)s    default:
        return 0;
    }
}
"""


def put_lines(m):
    names = {f["name"] for f in m["fields"]}
    pre, body = [], []
    for f in m["fields"]:
        t, n = f["type"], f["name"]
        if t == "str":
            if "count" in f:
                body.append("    for (int i = 0; i < %s; i++) {\n        put_str(w, m->%s[i], %s);\n"
                            "    }\n" % (c_value(f["count"]), n, c_value(f["cap"])))
            else:
                body.append("    put_str(w, m->%s, %s);\n" % (n, c_value(f["cap"])))
        elif t == "bytes":
            length = c_expr(f["length"], names, "(size_t)m->")
            pre.append("    if (!m->%s) {\n        return false;\n    }\n" % n)
            if f.get("max") is not None:
                pre.append("    for (size_t i = 0; i < %s; i++) {\n"
                           "        if (m->%s[i] > %s) {\n            return false;\n        }\n"
                           "    }\n" % (length, n, c_value(f["max"])))
            body.append("    bw_bytes(w, m->%s, %s);\n" % (n, length))
        elif t == "records":
            cn = f["count_name"]
            pre.append("    if (!(m->%s >= %s && m->%s <= %s)) {\n        return false;\n    }\n"
                       % (cn, c_value(f["min"]), cn, c_value(f["max"])))
            rec_fields = SPEC.records[f["record"]]["fields"]
            for rf in rec_fields:
                if explicit_range(rf):
                    pre.append("    for (int i = 0; i < m->%s; i++) {\n        if (!(%s)) {\n"
                               "            return false;\n        }\n    }\n"
                               % (cn, range_cond(rf, "m->%s[i].%s" % (n, rf["name"]))))
            body.append("    bw_%s(w, (%s)m->%s);\n" % (f["count_type"], {"u16": "uint16_t", "u8": "uint8_t", "u32": "uint32_t"}[f["count_type"]], cn))
            body.append("    for (int i = 0; i < m->%s; i++) {\n" % cn)
            for rf in rec_fields:
                body.append("        %s;\n" % PUT[rf["type"]].format(v="m->%s[i].%s" % (n, rf["name"])))
            body.append("    }\n")
        else:
            if explicit_range(f):
                if "count" in f:
                    pre.append("    for (int i = 0; i < %s; i++) {\n        if (!(%s)) {\n"
                               "            return false;\n        }\n    }\n"
                               % (c_value(f["count"]), range_cond(f, "m->%s[i]" % n)))
                else:
                    pre.append("    if (!(%s)) {\n        return false;\n    }\n"
                               % range_cond(f, "m->" + n))
            if "count" in f:
                body.append("    for (int i = 0; i < %s; i++) {\n        %s;\n    }\n"
                            % (c_value(f["count"]), PUT[t].format(v="m->%s[i]" % n)))
            else:
                body.append("    %s;\n" % PUT[t].format(v="m->" + n))
    for c in m.get("checks", []):
        pre.append("    if (!(%s)) { /* %s */\n        return false;\n    }\n"
                   % (c_expr(c["expr"], names), c["doc"]))
    return pre, body


def get_lines(m):
    names = {f["name"] for f in m["fields"]}
    body = []
    fail = "        return false;\n"
    for f in m["fields"]:
        t, n = f["type"], f["name"]
        if t == "str":
            if "count" in f:
                body.append("    for (int i = 0; i < %s; i++) {\n        get_str(&r, m->%s[i], %s);\n"
                            "    }\n" % (c_value(f["count"]), n, c_value(f["cap"])))
            else:
                body.append("    get_str(&r, m->%s, %s);\n" % (n, c_value(f["cap"])))
        elif t == "bytes":
            length = c_expr(f["length"], names, "(size_t)m->")
            body.append("    m->%s = br_view(&r, %s);\n    if (!m->%s) {\n%s    }\n"
                        % (n, length, n, fail))
            if f.get("max") is not None:
                body.append("    for (size_t i = 0; i < %s; i++) {\n        if (m->%s[i] > %s) {\n"
                            "            return false;\n        }\n    }\n"
                            % (length, n, c_value(f["max"])))
        elif t == "records":
            cn = f["count_name"]
            body.append("    m->%s = (int)br_%s(&r);\n" % (cn, f["count_type"]))
            body.append("    if (r.failed || m->%s < %s || m->%s > %s) {\n%s    }\n"
                        % (cn, c_value(f["min"]), cn, c_value(f["max"]), fail))
            body.append("    for (int i = 0; i < m->%s; i++) {\n" % cn)
            for rf in SPEC.records[f["record"]]["fields"]:
                var = "m->%s[i].%s" % (n, rf["name"])
                body.append("        %s = %s;\n" % (var, GET[rf["type"]]))
                if explicit_range(rf):
                    body.append("        if (!(%s)) {\n            return false;\n        }\n"
                                % range_cond(rf, var))
            body.append("    }\n")
        else:
            if "count" in f:
                body.append("    for (int i = 0; i < %s; i++) {\n        m->%s[i] = %s;\n"
                            % (c_value(f["count"]), n, GET[t]))
                if explicit_range(f):
                    body.append("        if (!(%s)) {\n            return false;\n        }\n"
                                % range_cond(f, "m->%s[i]" % n))
                body.append("    }\n")
            else:
                body.append("    m->%s = %s;\n" % (n, GET[t]))
                if explicit_range(f):
                    body.append("    if (r.failed || !(%s)) {\n%s    }\n"
                                % (range_cond(f, "m->" + n), fail))
    checks = "".join(" &&\n           (%s)" % c_expr(c["expr"], names) for c in m.get("checks", []))
    body.append("    return br_done(&r)%s;\n" % checks)
    return body


def gen_wire_c():
    asserts = "".join('_Static_assert(%s == %d, "protocol/messages.json: %s (%s)");\n'
                      % (k, v["value"], k, v["header"]) for k, v in SPEC.raw["external"].items())
    cases = {"C2S": "", "S2C": ""}
    for m in SPEC.messages:
        cases[m["dir"]] += "    case MSG_%s:\n        return WIRE_MAX_PAYLOAD_%s;\n" % (m["name"],
                                                                                    m["name"])
    out = [LICENSE, BANNER,
           WIRE_C_HELPERS % {"asserts": asserts, "client_cases": cases["C2S"],
                             "server_cases": cases["S2C"]}]
    for m in SPEC.messages:
        n, s = lower(m["name"]), m["struct"]
        pre, body = put_lines(m)
        out.append("\n/* --- MSG_%s %s */\n\n" % (m["name"], "-" * max(1, 64 - len(m["name"]))))
        out.append("bool wire_put_%s(BinWriter *w, const %s *m) {\n" % (n, s))
        out.extend(pre)
        out.append("    size_t at = frame_begin(w, MSG_%s);\n" % m["name"])
        out.extend(body)
        out.append("    return frame_end(w, at);\n}\n\n")
        out.append("bool wire_get_%s(const void *p, size_t n, %s *m) {\n" % (n, s))
        out.append("    BinReader r;\n    begin_read(&r, p, n, m, sizeof(*m));\n")
        out.extend(get_lines(m))
        out.append("}\n")
    return "".join(out)


# --- vectors ----------------------------------------------------------------

def invalid_variants(m, values):
    """(why, values or None, payload): payloads a decoder must refuse. With
    values, wire_put_ must refuse them too."""
    good = SPEC.encode(m["name"], values)
    out = []
    if good:
        out.append(("truncated by one byte", None, good[:-1]))
    out.append(("one trailing byte", None, good + b"\x00"))
    for f in m["fields"]:
        t = f["type"]
        if t in codec.SCALARS and explicit_range(f) and "count" not in f:
            lo, hi = SPEC.bounds(f)
            _fmt, _size, tlo, thi = codec.SCALARS[t]
            for bad in (lo - 1, hi + 1):
                if tlo <= bad <= thi:
                    v = dict(values, **{f["name"]: bad})
                    out.append(("%s = %d" % (f["name"], bad), v,
                                SPEC.encode(m["name"], v, check=False)))
        if t == "bool" and "count" not in f:
            v = dict(values, **{f["name"]: 2})
            out.append(("%s = 2 (not a bool)" % f["name"], None,
                        SPEC.encode(m["name"], v, check=False)))
        if t == "str" and "count" not in f:
            cap = SPEC.value(f["cap"])
            if cap <= 255:
                v = dict(values, **{f["name"]: "x" * cap})
                out.append(("%s of %d bytes" % (f["name"], cap), None,
                            SPEC.encode(m["name"], v, check=False)))
        if t == "bytes" and f.get("max") is not None and values[f["name"]]:
            v = dict(values, **{f["name"]: [SPEC.value(f["max"]) + 1] + values[f["name"]][1:]})
            out.append(("%s holds %d" % (f["name"], SPEC.value(f["max"]) + 1), v,
                        SPEC.encode(m["name"], v, check=False)))
        if t == "records":
            v = dict(values, **{f["name"]: []})
            out.append(("no %s" % f["name"], v, SPEC.encode(m["name"], v, check=False)))
    for c in m.get("checks", []):
        # Push the first field of the check past the limit.
        first = re.findall(r"\b[a-z_][a-z0-9_]*\b", c["expr"])[0]
        v = dict(values)
        while SPEC.value(c["expr"], v):
            v[first] += 1
        out.append(("%s fails" % c["expr"], v, SPEC.encode(m["name"], v, check=False)))
    return out


def vectors():
    valid, invalid = [], []
    for m in SPEC.messages:
        for i, ex in enumerate(m["examples"]):
            valid.append({"message": m["name"], "example": i, "values": ex,
                          "frame": SPEC.frame(m["name"], ex).hex()})
            for why, v, payload in invalid_variants(m, ex):
                invalid.append({"message": m["name"], "example": i, "why": why,
                                "values": v, "payload": payload.hex()})
    return {"$comment": "GENERATED by tools/gen_protocol.py from protocol/messages.json",
            "version": SPEC.version, "valid": valid, "invalid": invalid}


# --- conformance test -------------------------------------------------------

def c_bytes(data, indent="    "):
    items = ["0x%02x" % b for b in data]
    lines = []
    for i in range(0, len(items), 12):
        lines.append(indent + "    " + ", ".join(items[i:i + 12]) + ",")
    return "\n".join(lines) if lines else indent + "    0"


def c_string(s):
    return json.dumps(s, ensure_ascii=True)


def fill_lines(m, values, var="m"):
    out = []
    for f in m["fields"]:
        t, n = f["type"], f["name"]
        v = values[n]
        if t == "str":
            if "count" in f:
                for i, item in enumerate(v):
                    out.append("    set_str(%s.%s[%d], sizeof(%s.%s[%d]), %s);\n"
                               % (var, n, i, var, n, i, c_string(item)))
            else:
                out.append("    set_str(%s.%s, sizeof(%s.%s), %s);\n" % (var, n, var, n, c_string(v)))
        elif t == "bytes":
            out.append("    static const uint8_t %s_%s[] = {\n%s\n    };\n    %s.%s = %s_%s;\n"
                       % (var, n, c_bytes(v), var, n, var, n))
        elif t == "records":
            out.append("    %s.%s = %d;\n" % (var, f["count_name"], len(v)))
            for i, rec in enumerate(v):
                for rf in SPEC.records[f["record"]]["fields"]:
                    out.append("    %s.%s[%d].%s = %s;\n" % (var, n, i, rf["name"], rec[rf["name"]]))
        elif t in ("f32", "unit8"):
            items = v if "count" in f else [v]
            for i, item in enumerate(items):
                ix = "[%d]" % i if "count" in f else ""
                out.append("    %s.%s%s = %rf;\n" % (var, n, ix, float(item)))
        elif t == "u64":
            out.append("    %s.%s = %dULL;\n" % (var, n, v))
        elif t == "u32":
            out.append("    %s.%s = %du;\n" % (var, n, v))
        else:
            items = v if "count" in f else [v]
            for i, item in enumerate(items):
                ix = "[%d]" % i if "count" in f else ""
                out.append("    %s.%s%s = %d;\n" % (var, n, ix, item))
    return out


def compare_lines(m, a="m", b="d"):
    out = []
    names = {f["name"] for f in m["fields"]}
    for f in m["fields"]:
        t, n = f["type"], f["name"]
        if t == "str":
            if "count" in f:
                out.append("    for (int i = 0; i < %s; i++) {\n        CHECK(strcmp(%s.%s[i], %s.%s[i]) == 0);\n    }\n"
                           % (c_value(f["count"]), a, n, b, n))
            else:
                out.append("    CHECK(strcmp(%s.%s, %s.%s) == 0);\n" % (a, n, b, n))
        elif t == "bytes":
            length = c_expr(f["length"], names, "(size_t)%s." % a)
            out.append("    CHECK(%s.%s != NULL && memcmp(%s.%s, %s.%s, %s) == 0);\n"
                       % (b, n, a, n, b, n, length))
        elif t == "records":
            cn = f["count_name"]
            out.append("    CHECK(%s.%s == %s.%s);\n" % (a, cn, b, cn))
            out.append("    for (int i = 0; i < %s.%s; i++) {\n" % (a, cn))
            for rf in SPEC.records[f["record"]]["fields"]:
                out.append("        CHECK(%s.%s[i].%s == %s.%s[i].%s);\n"
                           % (a, n, rf["name"], b, n, rf["name"]))
            out.append("    }\n")
        else:
            def one(x, y):
                if t == "f32":
                    return "same_float(%s, %s)" % (x, y)
                if t == "unit8":
                    return "unit_byte(%s) == unit_byte(%s)" % (x, y)
                return "%s == %s" % (x, y)
            if "count" in f:
                out.append("    for (int i = 0; i < %s; i++) {\n        CHECK(%s);\n    }\n"
                           % (c_value(f["count"]), one("%s.%s[i]" % (a, n), "%s.%s[i]" % (b, n))))
            else:
                out.append("    CHECK(%s);\n" % one("%s.%s" % (a, n), "%s.%s" % (b, n)))
    return out


def gen_conformance(vec):
    out = [LICENSE, BANNER.replace("/* GENERATED", "/* GENERATED"), r"""
/*
 * Conformance of the C codec (src/shared/wire.c) with the table: every
 * example of protocol/messages.json is encoded to the exact bytes the
 * Python codec (protocol/codec.py) computes and decoded back field by
 * field; every invalid variant is refused by the decoder, and by the
 * encoder when it comes from an out-of-range value.
 */
#include <math.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>

#include "wire.h"

static int g_failures = 0;
static int g_checks = 0;
#define CHECK(cond)                                                                                \
    do {                                                                                           \
        g_checks++;                                                                                \
        if (!(cond)) {                                                                             \
            printf("FAIL %s:%d: %s\n", __FILE__, __LINE__, #cond);                                 \
            g_failures++;                                                                          \
        }                                                                                          \
    } while (0)

static void set_str(char *dst, size_t cap, const char *src) {
    snprintf(dst, cap, "%s", src);
}

/* Bit for bit: the wire carries the IEEE-754 bits. */
static int same_float(float a, float b) {
    uint32_t ua, ub;
    memcpy(&ua, &a, sizeof(ua));
    memcpy(&ub, &b, sizeof(ub));
    return ua == ub;
}

static int unit_byte(float f) {
    return (int)lroundf(f * 255.0f);
}

/* The writer holds exactly one frame: `want`. */
static void check_frame(const BinWriter *w, const uint8_t *want, size_t n) {
    CHECK(!w->failed);
    CHECK(w->len == n);
    CHECK(w->len == n && memcmp(w->data, want, n) == 0);
}
"""]
    tests = []
    by_msg = {m["name"]: m for m in SPEC.messages}
    for v in vec["valid"]:
        m = by_msg[v["message"]]
        n, s = lower(m["name"]), m["struct"]
        fn = "valid_%s_%d" % (n, v["example"])
        tests.append(fn)
        frame = bytes.fromhex(v["frame"])
        out.append("\nstatic void %s(void) {\n    static %s m, d;\n    memset(&m, 0, sizeof(m));\n" % (fn, s))
        out.extend(fill_lines(m, v["values"]))
        out.append("    static const uint8_t want[] = {\n%s\n    };\n" % c_bytes(frame))
        out.append("    BinWriter w;\n    bw_init(&w);\n    CHECK(wire_put_%s(&w, &m));\n"
                   "    check_frame(&w, want, sizeof(want));\n    bw_free(&w);\n" % n)
        out.append("    CHECK(wire_get_%s(want + WIRE_HEADER_SIZE, sizeof(want) - WIRE_HEADER_SIZE, &d));\n" % n)
        out.extend(compare_lines(m))
        out.append("}\n")
    for k, v in enumerate(vec["invalid"]):
        m = by_msg[v["message"]]
        n, s = lower(m["name"]), m["struct"]
        fn = "invalid_%s_%d" % (n, k)
        tests.append(fn)
        payload = bytes.fromhex(v["payload"])
        out.append("\n/* MSG_%s: %s */\nstatic void %s(void) {\n    static %s d;\n" % (m["name"], v["why"], fn, s))
        out.append("    static const uint8_t bad[] = {\n%s\n    };\n" % c_bytes(payload))
        out.append("    CHECK(!wire_get_%s(bad, %s, &d));\n" % (n, "sizeof(bad)" if payload else "0"))
        if v["values"] is not None:
            out.append("    static %s m;\n    memset(&m, 0, sizeof(m));\n" % s)
            out.extend(fill_lines(m, v["values"]))
            out.append("    BinWriter w;\n    bw_init(&w);\n    CHECK(!wire_put_%s(&w, &m));\n"
                       "    CHECK(w.len == 0);\n    bw_free(&w);\n" % n)
        out.append("}\n")
    out.append("\nint main(void) {\n")
    for t in tests:
        out.append("    %s();\n" % t)
    out.append('    if (g_failures) {\n        printf("%%d of %%d checks failed\\n", g_failures, g_checks);\n'
               '        return 1;\n    }\n'
               '    printf("protocol conformance: %d valid and %d invalid vectors, %%d checks passed\\n", g_checks);\n'
               '    return 0;\n}\n' % (len(vec["valid"]), len(vec["invalid"])))
    return "".join(out)


